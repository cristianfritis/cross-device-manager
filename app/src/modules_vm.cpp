// CONTROLLER AMENDMENT (D-9): shared helper instead of the two
// std::transform(..., ::tolower) call sites the plan specified — identical
// behavior for ASCII, and it removes real UB from passing a (possibly
// negative) plain `char` to ::tolower.
std::string toLowerCopy(std::string s) {
    std::ranges::transform(s, s.begin(),
                           [](unsigned char c) { return static_cast<char>(std::tolower(c)); });
    return s;
}

// Comma-joined module holders, truncated to the fixed column width.
std::string joinHolders(const std::vector<std::string>& holders) {
    std::string joined;
    for (const auto& h : holders) {
        if (!joined.empty()) joined += ",";
        joined += h;
    }
    static constexpr std::size_t kHoldersMaxLen = 24;
    static constexpr std::size_t kHoldersTruncatedLen = 21;
    if (joined.size() > kHoldersMaxLen) joined = joined.substr(0, kHoldersTruncatedLen) + "…";
    return joined;
}

// UTF-8 continuation bytes are 10xxxxxx; every other byte begins a codepoint.
constexpr unsigned char kUtf8ContinuationMask = 0xC0U;
constexpr unsigned char kUtf8ContinuationBits = 0x80U;

bool isContinuationByte(unsigned char c) {
    return (c & kUtf8ContinuationMask) == kUtf8ContinuationBits;
}

// Display width in terminal columns. Module names, signer names and the numeric
// cells are single-byte; the only multi-byte glyph these rows carry is the "…"
// ellipsis (three bytes, one column). Counting UTF-8 lead bytes is therefore
// exact here — and printf's byte-based `%-Ns` padding is not, which is why the
// signature cell is padded by hand below.
std::size_t displayWidth(std::string_view s) {
    std::size_t w = 0;
    for (const unsigned char c : s) {
        if (!isContinuationByte(c)) ++w;
    }
    return w;
}

// Drops the last whole codepoint (never half of a multi-byte sequence).
void popCodepoint(std::string& s) {
    if (s.empty()) return;
    s.pop_back();
    while (!s.empty() && isContinuationByte(static_cast<unsigned char>(s.back()))) s.pop_back();
}

// `cell` normalised to exactly `cols` display columns: padded with spaces, or
// ellipsis-truncated when it is wider. Keeps every column to the right of it in
// place — including while the async signature fill still shows "…".
std::string padTo(std::string cell, std::size_t cols) {
    if (displayWidth(cell) > cols) {
        while (displayWidth(cell) > cols - 1) popCodepoint(cell);
        cell += "…";
    }
    cell.append(cols - displayWidth(cell), ' ');
    return cell;
}

// Row cells, named so the two strings cannot be passed the wrong way round.
struct ModuleRowCells {
    std::string signature;  // "yes (signer)" | "yes" | "NO" | "?" | "…" (pending)
    std::string holders;    // comma-joined, already width-truncated
};

// Fixed-column module row (shared byte-for-byte with T11/T12 and with the GUI's
// ModuleListModel; the emitted format — NOT the brief prose — is authoritative
// per CONTROLLER AMENDMENT D-6).
//
// Column order is Name, Signed, Ref, Size, Used-by (pass-2 bug B5). Signed moved
// from last to second: it is what the user scans this list for, and at 80
// columns the row is clipped from the right, so the old order dropped the
// signature first and kept Used-by — exactly backwards. Used-by is now the
// widest, least load-bearing cell and the first to go.
std::string formatModuleRow(const core::LoadedModule& m, const ModuleRowCells& cells) {
    static constexpr std::size_t kRowBufferSize = 128;
    static constexpr std::uint64_t kBytesPerKb = 1024;
    // A signer name can be arbitrarily long ("yes (Build time autogenerated
    // kernel key)"); capped here so it cannot push Ref/Size/Used-by out of
    // alignment now that it is no longer the last cell. The detail pane carries
    // the full string. 20 is what the 80-column budget allows: the list pane is
    // 72 wide, leaving ~67 usable after the border, the "> " marker and the
    // scroll affordance, and Name(28)+1+Signed(20)+1+Ref(4)+1+Size(8)+2 = 65 —
    // so Name, Signed, Ref and Size all survive at 80 columns and Used-by is the
    // cell that clips.
    static constexpr std::size_t kSignedCols = 20;
    const std::string signedCell = padTo(cells.signature, kSignedCols);
    std::array<char, kRowBufferSize> row{};
    // snprintf is the only practical way to reproduce the fixed printf-style
    // column alignment shared byte-for-byte with T11/T12.
    // NOLINTNEXTLINE(cppcoreguidelines-pro-type-vararg)
    std::snprintf(row.data(), row.size(), "%-28s %s %4ld %7lluK  %s", m.name.c_str(),
                  signedCell.c_str(), m.refCount,
                  static_cast<unsigned long long>(m.sizeBytes / kBytesPerKb),
                  cells.holders.c_str());
    return {row.data()};
}

// "yes (signer)" | "yes" | "NO" for a resolved driver. The parenthesised signer
// appears only when there is one to name (pass-2 bug B5): a present-but-empty
// signer field rendered as the meaningless "yes ()".
std::string signatureLabel(const core::Driver& d) {
    if (!d.isSigned) return "NO";
    if (const auto& signer = d.signer; signer && !signer->empty()) return "yes (" + *signer + ")";
    return "yes";
}

// Signature-cell text for the row column: "?" when the module could not be
// classified, otherwise signatureLabel().
std::string signatureCellFor(const core::Result<core::Driver>& info) {
    return info ? signatureLabel(*info) : std::string("?");
}

// Maps the signature-column cell text to a colouring state (design decision
// 1a). "NO" → Unsigned, a "yes…" cell → Signed; "?" (unclassifiable) and "…"
// (async pending) both → Undetermined. Kept next to signatureCellFor() so the
// two agree on what the cell strings mean.
ModuleSignature classifySignatureCell(const std::string& cell) {
    if (cell == "NO") return ModuleSignature::Unsigned;
    if (cell.starts_with("yes")) return ModuleSignature::Signed;
    return ModuleSignature::Undetermined;
}

// Restores the highlighted module by name after a rebuild, then clamps.
int restoreSelection(const std::vector<std::optional<std::string>>& rowNames,
                     const std::optional<std::string>& keep, int current, int rowCount) {
    if (keep) {
        if (auto it = std::ranges::find(rowNames, keep); it != rowNames.end())
            current = static_cast<int>(std::distance(rowNames.begin(), it));
    }
    return std::clamp(current, 0, rowCount - 1);
}

void appendModuleInfo(std::vector<std::string>& out, const core::Result<core::Driver>& info) {
    if (!info) return;
    if (!info->version.empty()) out.push_back("Version: " + info->version);
    if (!info->path.empty()) out.push_back("Path:    " + info->path);
    out.push_back("Signed:  " + signatureLabel(*info));
    if (info->dependencies.empty()) return;
    std::string deps;
    for (const auto& d : info->dependencies) {
        if (!deps.empty()) deps += ", ";
        deps += d;
    }
    out.push_back("Depends: " + deps);
}

void appendModprobeInfo(std::vector<std::string>& out, const core::Result<core::ModprobeInfo>& mp) {
    if (!mp) return;
    if (const auto& options = mp->options) out.push_back("Options: " + *options);
    if (mp->blacklisted) out.emplace_back("modprobe.d: blacklisted");
}

